"""Regenerate the clickable category section of website/project-12.html from the project data.

Usage (from the repo root):
    python website/build_categories.py [data/model/model_results_final.json]

Replaces everything between <!-- CATEGORIES:START --> and <!-- CATEGORIES:END --> in website/project-12.html,
and the CSS between /* CATEGORIES-CSS:START */ and /* CATEGORIES-CSS:END */.
"""
import html, json, os, re, statistics, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "data", "model", "model_results_final.json")
PAGE = os.path.join(HERE, "project-12.html")

CATS = {
    1: ("AI Semiconductors: Compute &amp; Foundry", "AI"),
    2: ("AI Memory &amp; Semiconductor Equipment", "AI"),
    3: ("Hyperscalers &amp; AI Platforms", "AI"),
    4: ("Physical AI &amp; Robotics", "AI"),
    5: ("AI Power &amp; Data-Center Infrastructure", "AI + energy security"),
    6: ("AI Software &amp; Cybersecurity", "AI + cyber war"),
    7: ("US Defense Primes &amp; Defense Electronics", "War"),
    8: ("Defense Tech, Drones &amp; Allied Rearmament", "War"),
    9: ("Strategic Resources: Nuclear Fuel &amp; Critical Minerals", "War + AI power"),
    10: ("Biotech, Pandemic Preparedness &amp; AI Drug Discovery", "Pandemic"),
    11: ("Solar &amp; Renewables", "Energy transition"),
    12: ("Fintech &amp; Consumer", "Outside the 3 themes"),
    13: ("Theme Funds (ETFs and closed-end)", "Diversified"),
}
SHORT = {"SKHY": "SK hynix", "LYSDY": "Lynas", "RNMBY": "Rheinmetall", "BAESY": "BAE Systems", "FANUY": "FANUC",
         "KYCCF": "Keyence", "YASKY": "Yaskawa", "NOPMF": "Neo Performance", "3696": "Insilico", "ALM": "Almonty"}
TIER_TAG = {"A": "good", "B": "warn", "C": "", "D": "muted", "E": "bad"}
GROWTH_FWD = {"NVDA", "AVGO", "TSM", "AMD", "MU", "GOOGL", "VRT", "GEV", "PLTR", "CRWD", "RTX", "LMT", "NOC", "TMO"}

e = html.escape
pct = lambda v: "–" if v is None else f"{v*100:.0f}%"
pct1 = lambda v: "–" if v is None else f"{v:.0f}%"

R = json.load(open(DATA))

def growth(r):
    g = r.get("gused") if r["tk"] in GROWTH_FWD else r.get("cagr")
    return pct1(g)

def stock_rows(rs):
    out = []
    for i, r in enumerate(rs, 1):
        t = r["tier"][0]
        fund = r["cat"] == 13
        name = SHORT.get(r["tk"], "")
        label = f'<b>{e(name or r["tk"])}</b>' + (f' <span class="tkr">{e(r["tk"])}</span>' if name else "")
        ml = pct(r.get("ml")) + ("*" if r.get("ml_imputed") else "")
        out.append(
            f'<tr><td class="num">{i}</td>'
            f'<td>{label}<span class="cn">{e(r["name"])}</span></td>'
            f'<td class="num"><b>{pct(r["final"])}</b></td>'
            f'<td class="num">{ml} / {pct(r["rules"])}</td>'
            f'<td class="num">{pct(r.get("mlloss"))}</td>'
            + ("" if fund else
               f'<td class="num">{r.get("fs") if r.get("fs") is not None else "–"}</td>'
               f'<td class="num">{growth(r)}</td><td class="num">{pct1(r.get("opm"))}</td>'
               f'<td class="num">{e(str(r.get("pe_s") or "–"))}</td>')
            + f'<td><span class="tag {TIER_TAG[t]}" title="{e(r["tier"])}">{t}</span></td></tr>')
    return "\n".join(out)

blocks = []
for c in range(1, 14):
    rs = sorted([r for r in R if r["cat"] == c], key=lambda r: -r["final"])
    name, theme = CATS[c]
    avg = statistics.mean(r["final"] for r in rs)
    best = rs[0]
    num = str(c) if c <= 12 else "F"
    fund = c == 13
    head = ('<tr><th>#</th><th>Stock</th><th>Final P(2x)</th><th>ML / Rules</th><th>P(halves)</th>'
            + ("" if fund else "<th>Fin. score</th><th>Rev growth</th><th>Op margin</th><th>P/E</th>")
            + "<th>Tier</th></tr>")
    blocks.append(f'''<details class="catd" id="cat-{num.lower()}">
  <summary><span class="cnum">{num}</span><span class="cname">{name}<span class="ctheme">{theme} · {len(rs)} holdings</span></span><span class="cavg"><b>{pct(avg)}</b><small>avg P(2x)</small></span><span class="cbest">{e(SHORT.get(best["tk"], best["tk"]))} {pct(best["final"])}</span></summary>
  <div class="table-scroll"><table class="stk">
    <thead>{head}</thead>
    <tbody>
{stock_rows(rs)}
    </tbody>
  </table></div>
</details>''')

section = f'''<!-- CATEGORIES:START (generated by website/build_categories.py; edit the data, not this block) -->
      <div class="catbar"><p class="chart-note" style="margin:0">Click a category, or a bar in the chart, to see its stocks ranked by chance of doubling.</p><button type="button" class="cattoggle" id="cattoggle">Expand all</button></div>
      <div class="catlist">
{chr(10).join(blocks)}
      </div>
      <p style="font-size:13px;color:var(--muted);margin:12px 0 0">Final P(2x) = 50% trained ML model + 50% rules model. P(halves) = the ML model's chance the price ends at half or less. Fin. score = Financial Strength 0–100. Rev growth = latest-quarter growth where Q2/Q3 2026 results were reviewed, otherwise the 2-year revenue CAGR. * = too little price history; the universe median was used. Tiers: A 30%+ with strong finances and low loss risk · B 30%+, higher risk · C 25–29% · D 18–24% · E under 18%. Categories 11 and 12 were the v1 report's two legacy watchlists.</p>
      <script>
      (function(){{var ds=[].slice.call(document.querySelectorAll('details.catd')),btn=document.getElementById('cattoggle');
      function sync(){{btn.textContent=ds.every(function(d){{return d.open}})?'Collapse all':'Expand all';}}
      btn.addEventListener('click',function(){{var o=!ds.every(function(d){{return d.open}});ds.forEach(function(d){{d.open=o}});sync();}});
      ds.forEach(function(d){{d.addEventListener('toggle',sync);}});
      function openHash(){{var m=location.hash.match(/^#cat-(\\w+)$/);if(!m)return;var d=document.getElementById('cat-'+m[1]);if(d){{d.open=true;sync();d.scrollIntoView({{behavior:'smooth',block:'start'}});}}}}
      window.addEventListener('hashchange',openHash);openHash();
      var host=document.getElementById('cats');if(host){{host.style.cursor='pointer';host.addEventListener('click',function(ev){{var svg=host.querySelector('svg');if(!svg)return;var r=svg.getBoundingClientRect(),vb=svg.viewBox.baseVal,sx=(ev.clientX-r.left)*vb.width/r.width,L=46,R=8,n=12;var i=Math.floor((sx-L)/((vb.width-L-R)/n));if(i<0||i>=n)return;var d=ds[i];d.open=true;sync();d.scrollIntoView({{behavior:'smooth',block:'start'}});}});}}
      }})();
      </script>
<!-- CATEGORIES:END -->'''

css = '''/* CATEGORIES-CSS:START */
.catbar{display:flex;justify-content:space-between;align-items:center;gap:12px;flex-wrap:wrap;margin-top:14px}
.cattoggle{font:inherit;font-size:13px;font-weight:600;color:var(--accent);background:transparent;border:1px solid var(--line);border-radius:999px;padding:5px 14px;cursor:pointer}
.cattoggle:hover{border-color:var(--accent)}
.catlist{margin-top:10px;border-top:1px solid var(--line)}
details.catd{border-bottom:1px solid var(--line);scroll-margin-top:12px}
details.catd>summary{list-style:none;cursor:pointer;display:grid;grid-template-columns:34px minmax(0,1fr) 84px 120px 18px;gap:12px;align-items:center;padding:12px 4px}
details.catd>summary::-webkit-details-marker{display:none}
details.catd>summary::after{content:"";width:8px;height:8px;border-right:2px solid var(--muted);border-bottom:2px solid var(--muted);transform:rotate(45deg);justify-self:center;transition:transform .15s}
details.catd[open]>summary::after{transform:rotate(-135deg)}
details.catd>summary:hover .cname{color:var(--accent)}
details.catd>summary:focus-visible{outline:2px solid var(--accent);outline-offset:2px;border-radius:8px}
.cnum{width:30px;height:30px;border-radius:8px;display:grid;place-items:center;font-weight:700;font-size:13px;background:color-mix(in srgb,var(--accent) 14%,transparent);color:var(--accent)}
.cname{font-weight:600}.ctheme{display:block;font-weight:400;font-size:12.5px;color:var(--muted)}
.cavg{text-align:right;line-height:1.2}.cavg small{display:block;font-size:11px;color:var(--muted)}
.cbest{font-size:13px;color:var(--muted);text-align:right}
details.catd .table-scroll{margin:0 0 14px}
table.stk{font-size:13.5px}table.stk th{font-size:11.5px}table.stk td,table.stk th{padding:8px 10px}
table.stk .cn{display:block;font-size:12px;color:var(--muted)}table.stk .tkr{font-size:12px;color:var(--muted);font-weight:600}
@media (max-width:640px){details.catd>summary{grid-template-columns:30px minmax(0,1fr) 64px 16px}.cbest{display:none}}
/* CATEGORIES-CSS:END */'''

page = open(PAGE).read()
if "<!-- CATEGORIES:START" in page:
    page = re.sub(r"<!-- CATEGORIES:START.*?<!-- CATEGORIES:END -->", lambda m: section, page, flags=re.S)
else:
    # first run: replace the static category table and its footnote inside #categories12
    start = page.index('<div class="table-scroll" style="margin-top:14px"><table>', page.index('id="categories12"'))
    end_note = page.index("Categories 11 and 12 were the v1 report's two legacy watchlists.</p>", start)
    end = end_note + len("Categories 11 and 12 were the v1 report's two legacy watchlists.</p>")
    page = page[:start] + section + page[end:]
if "/* CATEGORIES-CSS:START */" in page:
    page = re.sub(r"/\* CATEGORIES-CSS:START \*/.*?/\* CATEGORIES-CSS:END \*/", lambda m: css, page, flags=re.S)
else:
    page = page.replace("</style>", css + "\n</style>", 1)
open(PAGE, "w").write(page)
print("updated", PAGE, len(page))
